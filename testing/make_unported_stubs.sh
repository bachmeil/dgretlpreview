#!/bin/bash
# Regenerate stubs_unported.d: one extern (C) D stub per libgretl function that is
# still referenced by the ported modules but not yet ported. Calling such a
# stub aborts with a message naming the function, so a test that reaches
# unported code fails loudly instead of silently returning garbage.
# Functions that tests need to work for real are defined in stubs.d; they are
# not undefined in the probe link below, so they get no stub here. The file is
# plain D: it compiles with dmd, ldmd2 or gdc, and needs no C compiler.
# Usage: testing/make_unported_stubs.sh   (run again after porting more files)
set -e
cd "$(dirname "$0")"
mkdir -p build
names=$(dmd -g -w -I.. -of=build/probe test_adf_kpss.d ../gretl/*.d ../gretl/plugin/*.d ../gretl/minpack/*.d ../cephes/*.d stubs.d \
        -L-lm -L-lxml2 -L-lz -L-llapack -L-lblas -L-lfftw3 2>&1 \
        | grep -o "undefined reference to \`[A-Za-z0-9_]*'" | sed "s/.*\`//; s/'//" | sort -u)
{
    echo '/* Generated by make_unported_stubs.sh -- do not edit. */'
    echo 'module stubs_unported;'
    echo
    echo 'import core.stdc.stdio: fprintf, stderr;'
    echo 'import core.stdc.stdlib: abort;'
    echo
    echo 'private void unported(string name) {'
    echo '    fprintf(stderr, "\n*** call to unported libgretl function %s()\n", name.ptr);'
    echo '    abort();'
    echo '}'
    echo
    for n in $names; do
        echo "extern (C) long $n() { unported(\"$n\"); return 0; }"
    done
} > stubs_unported.d
echo "wrote $(echo "$names" | wc -w) stubs to stubs_unported.d"
